import {test,expect} from '@playwright/test';
test('real browser account, profile, strict search, mobile and deletion',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  await page.screenshot({path:'/tmp/internmatch-signin.png',fullPage:true});
  await page.getByRole('button',{name:'New here? Create an account'}).click();
  await page.getByLabel('Email address').fill(`browser-${Date.now()}@example.com`);
  await page.getByLabel(/^Password/).fill('controlled browser test password');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Find your next beginning.'})).toBeVisible();
  await expect(page.getByRole('button',{name:/Strict Match/})).toHaveClass(/active/);
  await expect(page.getByText('Your next match is worth verifying.')).toBeVisible();
  await page.screenshot({path:'/tmp/internmatch-dashboard.png',fullPage:true});
  await page.getByRole('button',{name:'Profile',exact:true}).click();
  await page.getByLabel('University',{exact:true}).fill('Controlled Test University');
  await page.getByLabel('Expected graduation').fill('2030-05-01');
  await page.getByLabel('Confirmed standing at target start').fill('rising sophomore');
  await page.getByLabel('Target internship start').fill('2027-06-01');
  await expect(page.getByLabel('Authorized to work in the United States')).toHaveValue('');
  await page.getByRole('button',{name:'Confirm & save profile'}).click();
  await expect(page.getByRole('status')).toContainText('Confirmed qualifications saved');
  await page.reload();
  await page.getByRole('button',{name:'Profile',exact:true}).click();
  await expect(page.getByLabel('University',{exact:true})).toHaveValue('Controlled Test University');
  await expect(page.getByLabel('Authorized to work in the United States')).toHaveValue('');
  await page.getByRole('button',{name:'Applications',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your application journey.'})).toBeVisible();
  await page.getByRole('button',{name:'AI Analyst',exact:true}).click();
  await page.getByRole('textbox',{name:'Ask about stored opportunities'}).fill('cybersecurity');
  await page.getByRole('button',{name:'Find evidence'}).click();
  await expect(page.getByText('No stored postings match this query. This does not prove there are no openings.')).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Discover',exact:true}).click();
  await page.screenshot({path:'/tmp/internmatch-mobile.png',fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  expect(overflow).toBe(false);
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Settings & sources',exact:true}).click();
  await page.getByRole('button',{name:'Toggle color theme'}).click();
  await expect(page.locator('body')).toHaveClass('dark');
  await page.screenshot({path:'/tmp/internmatch-settings-dark.png',fullPage:true});
  page.once('dialog',d=>d.accept());
  await page.getByRole('button',{name:'Delete account',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  expect(errors).toEqual([]);
});
